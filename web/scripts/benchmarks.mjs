// Builds src/app/pages/benchmarks/benchmarks.data.ts from the evaluation results, so the page
// shows the numbers CI measures. Run with `pnpm benchmarks` after re-running eval/run.py.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const read = (path) => JSON.parse(readFileSync(resolve(repo, path), 'utf8'));

const local = read('eval/results/baseline.json');
const cohere = read('eval/results/cohere.json');
const search = read('docs/benchmarks/vector_search.json');

const recall5 = (run, mode) => run.modes[mode].all['recall@5'];

function provider(key, label, run, modes, best) {
  const top = run.modes[best];
  return {
    key,
    label,
    model: run.config.embedding_model.split(':').pop(),
    modes: modes.map((mode) => ({ mode, recall5: recall5(run, mode) })),
    kpis: {
      recall5: top.all['recall@5'],
      mrr10: top.all['mrr@10'],
      recall5En: top.by_lang.en['recall@5'],
      recall5Es: top.by_lang.es['recall@5'],
      p50Ms: top.latency_ms.p50,
    },
    threshold: run.abstention.suggested.threshold,
    sweep: run.abstention.sweep.map((s) => ({
      threshold: s.threshold,
      answered: s.answerable_coverage,
      refused: s.abstention_recall,
    })),
  };
}

const largest = search.results.at(-1);
const data = {
  corpus: {
    commit: local.corpus.peps_commit.slice(0, 7),
    documents: local.corpus.documents,
    chunks: local.corpus.chunks,
    questions: local.questions.answerable + local.questions.unanswerable,
    unanswerable: local.questions.unanswerable,
  },
  providers: [
    provider('local', 'Local', local, ['dense', 'lexical', 'hybrid'], 'hybrid'),
    provider('cohere', 'Cohere', cohere, ['dense', 'lexical', 'hybrid'], 'hybrid'),
    provider(
      'rerank',
      'Cohere + rerank',
      cohere,
      ['dense', 'lexical', 'hybrid', 'hybrid+rerank'],
      'hybrid+rerank',
    ),
  ],
  search: {
    chunks: largest.chunks,
    legacyMs: largest.legacy_python_p50_ms,
    exactMs: largest.pgvector_exact_p50_ms,
    hnswMs: largest.pgvector_hnsw_p50_ms,
  },
};

const out = resolve(here, '../src/app/pages/benchmarks/benchmarks.data.ts');
writeFileSync(
  out,
  `// Generated by scripts/benchmarks.mjs from eval/results and docs/benchmarks. Do not edit.\n` +
    `export const BENCHMARKS = ${JSON.stringify(data, null, 2)} as const;\n\n` +
    `export type Benchmarks = typeof BENCHMARKS;\n` +
    `export type Provider = Benchmarks['providers'][number];\n`,
);
console.log(`wrote ${out}`);
